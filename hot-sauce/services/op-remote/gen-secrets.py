"""Write op-remote's list of requestable secrets: one NAME=op://vault/item/field line per
hidden (CONCEALED) field in the given vaults. Values are never written, only
references, and op-remote reads a value only after Tanvi approves the request.

Run as _opremote by signin.sh:  python3 gen-secrets.py <out-file> <vault> [<vault>...]
Names read like ALT_INC__RENDER_API_KEY__CREDENTIAL so the Telegram approval message
says what is being asked for. References use IDs, so renaming an item doesn't break them.
"""
import json, re, subprocess, sys

out_path, vaults = sys.argv[1], sys.argv[2:]
dec = json.JSONDecoder()


def slug(s):
    return re.sub(r"[^A-Z0-9]+", "_", s.upper()).strip("_") or "X"


lines, seen = [], set()
for vault in vaults:
    listed = json.loads(subprocess.run(["op", "item", "list", "--vault", vault, "--format", "json"],
                                       capture_output=True, text=True, check=True).stdout)
    # `op item get -` stops the whole batch at the first item it can't read (e.g. an
    # SSH key with an unparseable private key: "unable to process element 24"). So
    # feed the batch again from after the bad item, until every item is tried.
    got, start = "", 0
    while start < len(listed):
        res = subprocess.run(["op", "item", "get", "-", "--format", "json"],
                             input=json.dumps(listed[start:]), capture_output=True, text=True)
        got += res.stdout + "\n"
        if res.returncode == 0:
            break
        # Whatever the error, the bad item is the one after the last item that came back.
        returned, i = 0, 0
        while i < len(res.stdout):
            while i < len(res.stdout) and res.stdout[i].isspace():
                i += 1
            if i >= len(res.stdout):
                break
            _, i = dec.raw_decode(res.stdout, i)
            returned += 1
        bad = start + returned
        if bad >= len(listed):
            break
        why = res.stderr.strip().splitlines()[-1][:150] if res.stderr.strip() else "no error text"
        print(f"{vault}: skipped {listed[bad]['title']!r} ({why})", file=sys.stderr)
        start = bad + 1
    i = 0
    while i < len(got):
        while i < len(got) and got[i].isspace():
            i += 1
        if i >= len(got):
            break
        item, i = dec.raw_decode(got, i)
        for f in item.get("fields", []):
            if f.get("type") != "CONCEALED" or not f.get("value"):
                continue
            name = "__".join([slug(vault), slug(item["title"]), slug(f.get("label") or f["id"])])
            base, n = name, 2
            while name in seen:
                name, n = f"{base}_{n}", n + 1
            seen.add(name)
            # "#:" line: the readable label op-remote's patched Telegram message shows.
            label = f"{vault} › {item['title']} › {f.get('label') or f['id']}".replace("\n", " ")
            lines.append(f"#: {name}\t{label}\n{name}=op://{item['vault']['id']}/{item['id']}/{f['id']}")
    del got

with open(out_path, "w") as fh:
    fh.write("# Generated by gen-secrets.py at sign-in. References only, no values.\n")
    fh.write("\n".join(sorted(lines)) + "\n")
print(f"Listed {len(lines)} secrets from {', '.join(vaults)}")
